# Render every line in tools/lines.json with Google Chirp 3 HD (da-DK) → audio/v/<id>.mp3, then write js/voices.js.
# Key: GOOGLE_TTS_KEYFILE (service-account JSON, never committed).
import json, os, sys, time, base64, subprocess, urllib.request, urllib.error, threading
from concurrent.futures import ThreadPoolExecutor
import jwt
ROOT = os.path.join(os.path.dirname(__file__), '..')
KEY = os.environ.get('GOOGLE_TTS_KEYFILE') or sys.exit('Set GOOGLE_TTS_KEYFILE')
k = json.load(open(KEY))
_tok = [None, 0]; lock = threading.Lock()
def token():
    with lock:
        if time.time() > _tok[1] - 300:
            now = int(time.time())
            _tok[0] = jwt.encode({'iss': k['client_email'], 'sub': k['client_email'], 'aud': 'https://texttospeech.googleapis.com/', 'iat': now, 'exp': now + 3600}, k['private_key'], algorithm='RS256', headers={'kid': k['private_key_id']})
            _tok[1] = now + 3600
        return _tok[0]
RATE = {'gun': 0.95, 'lilla': 1.08, 'auctioneer': 1.12, 'donor1': 1.05, 'donor2': 1.05, 'donor3': 1.0, 'sok': 0.9}
OUT = os.path.join(ROOT, 'audio', 'v'); os.makedirs(OUT, exist_ok=True)
lines = json.load(open(os.path.join(ROOT, 'tools', 'lines.json')))
def render(l):
    dest = os.path.join(OUT, l['id'] + '.mp3')
    if os.path.exists(dest): return 'skip'
    text = l['text'] if l['text'] != '…' else '…'
    body = json.dumps({'input': {'text': text}, 'voice': {'languageCode': 'da-DK', 'name': f"da-DK-Chirp3-HD-{l['voice']}"},
                       'audioConfig': {'audioEncoding': 'MP3', 'speakingRate': RATE.get(l['who'], 1.0)}}).encode()
    for attempt in range(6):
        try:
            req = urllib.request.Request('https://texttospeech.googleapis.com/v1/text:synthesize', data=body, headers={'Content-Type': 'application/json', 'Authorization': 'Bearer ' + token()})
            d = json.loads(urllib.request.urlopen(req, timeout=60).read())
            raw = base64.b64decode(d['audioContent'])
            if l['who'] in ('gun', 'sok'):
                tmp = dest + '.raw.mp3'; open(tmp, 'wb').write(raw)
                af = 'aecho=0.8:0.6:40|80:0.3|0.2,bass=g=4' if l['who'] == 'gun' else 'asetrate=24000*0.92,aresample=24000,aecho=0.8:0.5:30:0.3'
                subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', tmp, '-af', af, '-ac', '1', '-b:a', '64k', dest], check=True); os.remove(tmp)
            else:
                open(dest, 'wb').write(raw)
            return 'ok'
        except urllib.error.HTTPError as e:
            msg = e.read().decode()[:200]
            if e.code in (429, 500, 503): time.sleep(3 + attempt * 4); continue
            return 'fail %s %s %s' % (e.code, l['text'], msg)
        except Exception as e:
            time.sleep(2); last = str(e)
    return 'fail ' + l['text']
with ThreadPoolExecutor(6) as ex:
    res = list(ex.map(render, lines))
fails = [r for r in res if r.startswith('fail')]
print('ok', res.count('ok'), 'skip', res.count('skip'), 'fail', len(fails)); [print(f) for f in fails[:10]]
have = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith('.mp3'))
ids = {l['id'] for l in lines}
open(os.path.join(ROOT, 'js', 'voices.js'), 'w').write('// generated by tools/voices.py\nwindow.K = window.K || {}; K.VOICES = {' + ','.join('"%s":1' % i for i in have if i in ids) + '};\n')
